export const LEVELS_BY_SLUG = new Map(CURRICULUM.map((l) => [l.slug, l]));

export function findLevel(slug: string): Level | undefined {
  return LEVELS_BY_SLUG.get(slug);
}

export function nextLevel(slug: string): Level | undefined {
  const index = CURRICULUM.findIndex((l) => l.slug === slug);
  return index >= 0 ? CURRICULUM[index + 1] : undefined;
}

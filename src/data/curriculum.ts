const K = (n: number) => ["០", "១", "២", "៣", "៤", "៥", "៦", "៧", "៨", "៩"][n] ?? String(n);

export const khmerNumber = (n: number): string =>
  String(n)
    .split("")
    .map((d) => K(Number(d)))
    .join("");


export type LessonMode = "keys" | "words" | "text" | "exam";

export type Lesson = {
  id: string;
  title: string;
  /** short Khmer instruction shown above the exercise */
  hint?: string;
  mode: LessonMode;
  /** each line is one exercise round */
  lines: string[];
  /** optional time limit in seconds (used by the capstone exam) */
  timeLimit?: number;
};

export type Level = {
  id: number;
  slug: string;
  /** e.g. "កម្រិតទី ១" */
  badge: string;
  title: string;
  summary: string;
  stage: string;
  focus: string[];
  lessons: Lesson[];
};

const K = (n: number) => ["០", "១", "២", "៣", "៤", "៥", "៦", "៧", "៨", "៩"][n] ?? String(n);

export const khmerNumber = (n: number): string =>
  String(n)
    .split("")
    .map((d) => K(Number(d)))
    .join("");

